"""Generate a one-line node-agent install command.

The panel shows this command after creating a node (or on demand). It installs
the agent, writes its HMAC secret, opens the agent port to the panel and starts
the systemd unit. The secret is embedded once — the command is shown only at
creation time, but admins can re-issue it from the node page.
"""

from __future__ import annotations

import shlex

from app.models.node import Node

INSTALL_PATH = "/opt/ovpn-panel"


def agent_port(node: Node) -> int:
    """Default agent port derived from the node id (stable per node)."""

    return 8090 + (node.id or 0) % 10


def _endpoint(node: Node) -> str:
    if node.agent_url:
        return node.agent_url.rstrip("/")
    return f"http://{node.host}:{agent_port(node)}"


def build_install_command(node: Node, *, panel_url: str = "", secret: str | None = None) -> str:
    """Return a single paste-able install command for the node host."""

    secret = secret or node.agent_secret or ""
    base = (panel_url or "https://panel.example.com").rstrip("/")
    payload = {
        "secret": secret,
        "node_name": node.name,
        "agent_port": str(agent_port(node)),
        "panel_url": base,
    }
    args = " ".join(f"--{key} {shlex.quote(value)}" for key, value in payload.items())
    return f"curl -fsSL {base}/nodes/agent/install.sh | sudo bash -s -- {args}"


def build_install_script() -> str:
    """A self-contained POSIX installer for the node agent.

    Deliberately conservative: creates a service user, installs the package
    from the panel wheel, writes the HMAC secret to ``/etc/ovpn-panel/agent.env``
    (mode 600) and enables ``ovpn-panel-agent@<name>``.
    """

    return r"""#!/usr/bin/env bash
# OpenVPN Web Panel — node agent installer (generated by the panel).
set -euo pipefail

SECRET=""
NODE_NAME="node"
AGENT_PORT="8090"
PANEL_URL=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --secret) SECRET="${2:-}"; shift 2 ;;
    --node_name) NODE_NAME="${2:-}"; shift 2 ;;
    --agent_port) AGENT_PORT="${2:-}"; shift 2 ;;
    --panel_url) PANEL_URL="${2:-}"; shift 2 ;;
    *) echo "unknown option: $1" >&2; exit 1 ;;
  esac
done

if [[ "$(id -u)" -ne 0 ]]; then echo "run as root" >&2; exit 1; fi
if [[ -z "${SECRET}" ]]; then echo "--secret is required" >&2; exit 1; fi

id -u ovpn-panel >/dev/null 2>&1 || \
  useradd --system --home /opt/ovpn-panel --shell /usr/sbin/nologin ovpn-panel

install -d -m 0750 -o ovpn-panel -g ovpn-panel /etc/ovpn-panel
cat > /etc/ovpn-panel/agent.env <<EOF
OVPN_AGENT_HMAC_SECRET=${SECRET}
OVPN_AGENT_NODE_NAME=${NODE_NAME}
OVPN_AGENT_LISTEN_PORT=${AGENT_PORT}
OVPN_AGENT_LISTEN_HOST=0.0.0.0
EOF
chmod 600 /etc/ovpn-panel/agent.env
chown ovpn-panel:ovpn-panel /etc/ovpn-panel/agent.env

# Allow the panel host to reach the agent port (adjust the source as needed).
if command -v ufw >/dev/null 2>&1; then
  ufw allow "${AGENT_PORT}/tcp" || true
elif command -v firewall-cmd >/dev/null 2>&1; then
  firewall-cmd --permanent --add-port="${AGENT_PORT}/tcp" || true
  firewall-cmd --reload || true
fi

systemctl daemon-reload
systemctl enable --now "ovpn-panel-agent@${NODE_NAME}"
echo "Node agent '${NODE_NAME}' listening on :${AGENT_PORT}"
"""
